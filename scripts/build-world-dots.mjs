// build-world-dots — pre-render the Monitor page's dot-matrix world map.
//
// Samples a regular grid in Miller-projected space against Natural Earth land
// (world-atlas TopoJSON) and writes the land mask as a base64 bitmap to
// src/components/monitor/worldDots.ts. Sampling in projected space keeps the dots
// evenly spaced on screen. The page then draws the map with the same Miller formula:
// no d3, no tiles, no network (the site's CSP blocks external connections), and
// nothing added to package.json. Run once; re-run only to change the grid.
//
//   npm pack world-atlas@2.0.2 && tar -xzf world-atlas-2.0.2.tgz   (any scratch folder)
//   node scripts/build-world-dots.mjs <scratch>/package/land-50m.json
//
// Miller (not equirectangular) because it is ~2:1 rather than ~2.5:1 once Antarctica
// is cropped, so the map can fill most of a desktop viewport at full width. The grid
// stops at 57°S: no tracked word's coverage is in Antarctica.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const LON_MIN = -180;
const LAT_MAX = 84;
const LAT_MIN = -57;
const COLS = 240;

const rad = Math.PI / 180;
const miller = (lat) => 1.25 * Math.log(Math.tan(Math.PI / 4 + 0.4 * lat * rad));
const millerInv = (y) => (2.5 * Math.atan(Math.exp(0.8 * y)) - (5 * Math.PI) / 8) / rad;
const Y_MAX = miller(LAT_MAX);
const Y_MIN = miller(LAT_MIN);
const ROWS = Math.round((COLS * (Y_MAX - Y_MIN)) / (2 * Math.PI));

const src = process.argv[2];
if (!src) {
  console.error('usage: node scripts/build-world-dots.mjs <path/to/world-atlas/land-50m.json>');
  process.exit(1);
}
const topo = JSON.parse(readFileSync(src, 'utf8'));

// TopoJSON decode: quantized, delta-encoded arcs → absolute lon/lat.
const [sx, sy] = topo.transform.scale;
const [tx, ty] = topo.transform.translate;
const arcs = topo.arcs.map((arc) => {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => {
    x += dx;
    y += dy;
    return [x * sx + tx, y * sy + ty];
  });
});
const arcPoints = (i) => (i >= 0 ? arcs[i] : arcs[~i].slice().reverse());
const ringPoints = (idxs) => {
  const pts = [];
  idxs.forEach((i, k) => {
    const a = arcPoints(i);
    pts.push(...(k ? a.slice(1) : a));
  });
  return pts;
};

const rings = [];
const addGeometry = (g) => {
  if (g.type === 'GeometryCollection') g.geometries.forEach(addGeometry);
  else if (g.type === 'Polygon') g.arcs.forEach((r) => rings.push(ringPoints(r)));
  else if (g.type === 'MultiPolygon') g.arcs.forEach((p) => p.forEach((r) => rings.push(ringPoints(r))));
};
addGeometry(topo.objects.land);

// Even-odd ray cast across every ring (holes are inner rings, so lakes stay empty).
function onLand(lon, lat) {
  let inside = false;
  for (const r of rings) {
    for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
      const [xi, yi] = r[i];
      const [xj, yj] = r[j];
      if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
    }
  }
  return inside;
}

const bits = new Uint8Array(Math.ceil((COLS * ROWS) / 8));
let land = 0;
for (let r = 0; r < ROWS; r++) {
  const lat = millerInv(Y_MAX - ((r + 0.5) / ROWS) * (Y_MAX - Y_MIN));
  for (let c = 0; c < COLS; c++) {
    const lon = LON_MIN + ((c + 0.5) / COLS) * 360;
    if (onLand(lon, lat)) {
      const i = r * COLS + c;
      bits[i >> 3] |= 1 << (i & 7);
      land++;
    }
  }
}

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(here, '..', 'src', 'components', 'monitor', 'worldDots.ts');
writeFileSync(
  out,
  `// GENERATED by scripts/build-world-dots.mjs from world-atlas ${path.basename(src)}
// (Natural Earth, public domain). Do not edit by hand. Miller projection, ${COLS}×${ROWS}
// grid evenly spaced in projected space, ${land} land cells, ${LAT_MAX}°N to ${Math.abs(LAT_MIN)}°S,
// row-major from the top-left, LSB-first bitmap.
export const WORLD_DOTS = {
  lonMin: ${LON_MIN},
  latMax: ${LAT_MAX},
  latMin: ${LAT_MIN},
  cols: ${COLS},
  rows: ${ROWS},
  mask: '${Buffer.from(bits).toString('base64')}',
} as const;
`
);
console.log(`wrote ${out}: ${COLS}x${ROWS} (aspect ${(COLS / ROWS).toFixed(3)}), ${land} land cells`);
