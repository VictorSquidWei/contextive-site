// build-world-dots — pre-render the Monitor page's dot-matrix world map.
//
// Samples a regular lon/lat grid against Natural Earth land (world-atlas TopoJSON)
// and writes the land mask as a base64 bitmap to src/components/monitor/worldDots.ts.
// The page then draws the map with plain equirectangular math: no d3, no tiles, no
// network (the site's CSP blocks external connections), and nothing added to
// package.json. Run once; re-run only to change the grid.
//
//   npm pack world-atlas@2.0.2 && tar -xzf world-atlas-2.0.2.tgz   (any scratch folder)
//   node scripts/build-world-dots.mjs <scratch>/package/land-50m.json
//
// Antarctica is cropped (the grid stops at 57°S): no tracked word's coverage is there,
// and it would take a fifth of the map's height.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const STEP = 1.5;
const LON_MIN = -180;
const LAT_MAX = 84;
const LAT_MIN = -57;
const COLS = Math.round(360 / STEP);
const ROWS = Math.round((LAT_MAX - LAT_MIN) / STEP);

const src = process.argv[2];
if (!src) {
  console.error('usage: node scripts/build-world-dots.mjs <path/to/world-atlas/land-50m.json>');
  process.exit(1);
}
const topo = JSON.parse(readFileSync(src, 'utf8'));

// TopoJSON decode: quantized, delta-encoded arcs → absolute lon/lat.
const [sx, sy] = topo.transform.scale;
const [tx, ty] = topo.transform.translate;
const arcs = topo.arcs.map((arc) => {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => {
    x += dx;
    y += dy;
    return [x * sx + tx, y * sy + ty];
  });
});
const arcPoints = (i) => (i >= 0 ? arcs[i] : arcs[~i].slice().reverse());
const ringPoints = (idxs) => {
  const pts = [];
  idxs.forEach((i, k) => {
    const a = arcPoints(i);
    pts.push(...(k ? a.slice(1) : a));
  });
  return pts;
};

const rings = [];
const addGeometry = (g) => {
  if (g.type === 'GeometryCollection') g.geometries.forEach(addGeometry);
  else if (g.type === 'Polygon') g.arcs.forEach((r) => rings.push(ringPoints(r)));
  else if (g.type === 'MultiPolygon') g.arcs.forEach((p) => p.forEach((r) => rings.push(ringPoints(r))));
};
addGeometry(topo.objects.land);

// Even-odd ray cast across every ring (holes are inner rings, so lakes stay empty).
function onLand(lon, lat) {
  let inside = false;
  for (const r of rings) {
    for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
      const [xi, yi] = r[i];
      const [xj, yj] = r[j];
      if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
    }
  }
  return inside;
}

const bits = new Uint8Array(Math.ceil((COLS * ROWS) / 8));
let land = 0;
for (let r = 0; r < ROWS; r++) {
  const lat = LAT_MAX - (r + 0.5) * STEP;
  for (let c = 0; c < COLS; c++) {
    const lon = LON_MIN + (c + 0.5) * STEP;
    if (onLand(lon, lat)) {
      const i = r * COLS + c;
      bits[i >> 3] |= 1 << (i & 7);
      land++;
    }
  }
}

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(here, '..', 'src', 'components', 'monitor', 'worldDots.ts');
writeFileSync(
  out,
  `// GENERATED by scripts/build-world-dots.mjs from world-atlas ${path.basename(src)}
// (Natural Earth, public domain). Do not edit by hand. ${COLS}×${ROWS} grid at ${STEP}°,
// ${land} land cells, row-major from ${LAT_MAX}°N / ${LON_MIN}°E, LSB-first bitmap.
export const WORLD_DOTS = {
  step: ${STEP},
  lonMin: ${LON_MIN},
  latMax: ${LAT_MAX},
  latMin: ${LAT_MIN},
  cols: ${COLS},
  rows: ${ROWS},
  mask: '${Buffer.from(bits).toString('base64')}',
} as const;
`
);
console.log(`wrote ${out}: ${COLS}x${ROWS}, ${land} land cells`);
